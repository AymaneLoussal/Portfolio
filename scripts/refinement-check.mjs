import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true});
await page.goto('http://127.0.0.1:4173');
await page.waitForTimeout(1800);
assert.equal(await page.locator('.world-nav a').count(),3);
await page.locator('#mobile-menu-toggle').click();await page.keyboard.press('Escape');
assert.equal(await page.locator('#mobile-menu-toggle').getAttribute('aria-expanded'),'false');
await page.emulateMedia({reducedMotion:'reduce'});
assert.equal(await page.locator('.transition-stage').first().evaluate(e=>getComputedStyle(e).position),'relative');
await page.locator('#sound-toggle-btn').click();await page.locator('#sound-toggle-btn').click();
assert.equal(await page.locator('#sound-toggle-btn').getAttribute('aria-pressed'),'false');
const plain=await browser.newPage({javaScriptEnabled:false,viewport:{width:390,height:844}});
await plain.goto('http://127.0.0.1:4173');
assert(await plain.locator('.desktop-nav').isVisible());
assert(!await plain.locator('#sound-toggle-btn').isVisible());
assert(!await plain.locator('.project-open').first().isVisible());
assert((await plain.locator('.editorial-card').first().getAttribute('href')).endsWith('.jpg'));
await plain.locator('.desktop-nav a[href="#football"]').click();
assert.equal(new URL(plain.url()).hash,'#football');
await browser.close();
console.log('V5.1 regressions passed: normal-flow navigation, 44px targets, Escape, reduced motion, sound toggle, no-JS links and gallery.');
